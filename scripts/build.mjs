import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  outfile: 'dist/index.ts',
  write: false,
  sourcemap: false,
  legalComments: 'none',
  banner: { js: '// Generated by npm run build. MIT licensed. Do not edit by hand.\n// Single-file .ts entrypoint lets Pi reload without stale native-ESM helper modules.' },
});
const output = result.outputFiles[0].text;
const destination = join(root, 'dist/index.ts');
if (process.argv.includes('--check')) {
  let existing;
  try { existing = readFileSync(destination, 'utf8'); }
  catch { throw new Error('Missing committed bundle. Run npm run build.'); }
  if (existing !== output) throw new Error('Committed bundle is stale. Run npm run build.');
  console.log('Bundle is reproducible and up to date.');
} else {
  mkdirSync(join(root, 'dist'), { recursive: true });
  writeFileSync(destination, output);
  console.log('Built dist/index.ts (single file; no local runtime imports).');
}
